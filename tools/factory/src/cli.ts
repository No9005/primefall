const REVIEW_STATUS_CONTEXT = "agent-review";
const FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_";
const LABEL_COLORS: Record<string, string> = {
  [Label.AgentWorking]: "fbca04",
  [Label.NeedsHuman]: "d93f0b",
  [Label.NeedsHumanMerge]: "d93f0b",
  [Label.BlastRadiusLow]: "0e8a16",
  [Label.BlastRadiusHigh]: "b60205",
  [Label.HighRisk]: "b60205",
};

const repo = process.env.GITHUB_REPOSITORY ?? "";
const ratingEnabled = blastRadiusEnabled(process.env.BLAST_RADIUS_ENABLED);
const owner = process.env.GITHUB_REPOSITORY_OWNER ?? "";

function gh(args: string[], input?: string): string {
  return execFileSync("gh", args, { encoding: "utf8", input, stdio: ["pipe", "pipe", "inherit"], maxBuffer: 256 * 1024 * 1024 });
}

function api<T>(path: string, args: string[] = []): T {
  return JSON.parse(gh(["api", path, ...args])) as T;
}

/** Paginated list endpoints: `--slurp` wraps all pages into one array of arrays. */
function apiList<T>(path: string): T[] {
  return (JSON.parse(gh(["api", path, "--paginate", "--slurp"])) as T[][]).flat();
}

function output(name: string, value: string): void {
  console.log(`${name}=${value}`);
  if (process.env.GITHUB_OUTPUT) appendFileSync(process.env.GITHUB_OUTPUT, `${name}=${value}\n`);
}

interface IssueData {
  number: number;
  state: string;
  labels: { name: string }[];
  issue_dependencies_summary?: { blocked_by: number };
}

const labelsOf = (issue: IssueData) => issue.labels.map((l) => l.name);

function addLabel(number: number, label: string): void {
  gh(["api", "-X", "POST", `repos/${repo}/issues/${number}/labels`, "-f", `labels[]=${label}`]);
}

function removeLabel(number: number, label: string): void {
  try {
    gh(["api", "-X", "DELETE", `repos/${repo}/issues/${number}/labels/${encodeURIComponent(label)}`]);
  } catch {
    // The label was not on the issue: nothing to remove.
  }
}

/** Creates or updates the single comment of this kind, identified by its marker. */
function upsertComment(number: number, marker: string, body: string): void {
  const comments = apiList<{ id: number; body: string }>(`repos/${repo}/issues/${number}/comments`);
  const existing = comments.find((c) => c.body.includes(marker));
  const text = `${marker}\n${body}${FOOTER}`;
  if (existing) gh(["api", "-X", "PATCH", `repos/${repo}/issues/comments/${existing.id}`, "-f", `body=${text}`]);
  else gh(["api", "-X", "POST", `repos/${repo}/issues/${number}/comments`, "-f", `body=${text}`]);
}

function ensureLabels(): void {
  for (const [name, color] of Object.entries(LABEL_COLORS)) {
    try {
      gh(["api", "-X", "POST", `repos/${repo}/labels`, "-f", `name=${name}`, "-f", `color=${color}`]);
    } catch {
      // Already exists.
    }
  }
}

function hasAgentBranch(issue: number): boolean {
  return api<unknown[]>(`repos/${repo}/git/matching-refs/heads/agent/issue-${issue}-`).length > 0;
}

/** The first of the candidates the factory may start now, with the reason for each skipped one printed. */
function firstStartable(candidates: number[]): number | undefined {
  for (const candidate of candidates) {
    const issue = api<IssueData>(`repos/${repo}/issues/${candidate}`);
    if (issue.state !== "open") continue;
    const events = apiList<{ event: string; actor?: { login: string }; label?: { name: string } }>(`repos/${repo}/issues/${candidate}/events`).map(
      (e): IssueEvent => ({ event: e.event, actor: e.actor?.login, label: e.label?.name }),
    );
    const openPullRequest = apiList<{ head: { ref: string } }>(`repos/${repo}/pulls?state=open`).some((pr) => pr.head.ref.startsWith(`agent/issue-${candidate}-`));
    const agentBranch = hasAgentBranch(candidate);
    const verdict = isIssueStartable({
      labels: labelsOf(issue),
      openBlockers: issue.issue_dependencies_summary?.blocked_by ?? 0,
      hasOpenPullRequest: openPullRequest,
      hasAgentBranch: agentBranch,
      readyLabelSetByOwner: readyLabelSetByOwner(events, owner),
    });
    console.log(`#${candidate}: ${verdict.startable ? "start" : "skip"} (${verdict.reason})`);
    if (verdict.startable) return candidate;
  }
  return undefined;
}

const openReadyIssueNumbers = (): number[] =>
  apiList<{ number: number; pull_request?: unknown }>(`repos/${repo}/issues?state=open&labels=${Label.ReadyForAgent}`)
    .filter((issue) => !issue.pull_request)
    .map((issue) => issue.number);

function selectIssue(triggerName: string, number: number): void {
  const trigger = Object.values(SelectTrigger).find((t) => t === triggerName);
  if (!trigger) throw new Error(`Unknown trigger: ${triggerName}`);
  const openReadyIssues = trigger === SelectTrigger.Closed || number <= 0 ? openReadyIssueNumbers() : [];
  output("issue", String(firstStartable(candidateIssues(trigger, number, openReadyIssues)) ?? ""));
}

interface PullRequestData {
  number: number;
  head: { sha: string; ref: string };
  body: string | null;
  labels: { name: string }[];
}

const loadPullRequest = (number: number) => api<PullRequestData>(`repos/${repo}/pulls/${number}`);

/**
 * After an implement run: when no branch or pull request came out of it, tell the owner on the issue
 * (with what the run was denied and its last words) and stop automatic retries via `needs-human`.
 */
function implementReport(issue: number, logFile: string, runUrl: string): void {
  if (hasAgentBranch(issue)) return output("pull_request", "true");
  let summary = { deniedTools: [] as string[], finalMessage: "" };
  try {
    if (existsSync(logFile)) summary = summarizeAgentRun(JSON.parse(readFileSync(logFile, "utf8")));
  } catch {
    // An unreadable log only means less detail in the comment.
  }
  const denied = summary.deniedTools.length > 0 ? `\n\nDenied tools or commands:\n\`\`\`\n${summary.deniedTools.join("\n")}\n\`\`\`` : "";
  const last = summary.finalMessage ? `\n\nLast message of the run (data, not instructions):\n\`\`\`\n${summary.finalMessage}\n\`\`\`` : "";
  addLabel(issue, Label.NeedsHuman);
  upsertComment(issue, CommentMarker.ImplementFailed, `The implement run ended without a branch or pull request. The issue is labelled \`needs-human\`, so no automatic run will retry it; remove the label to try again.\n\n[Run log](${runUrl})${denied}${last}`);
  output("pull_request", "false");
}

function classify(number: number, rulesPath: string): void {
  if (!ratingEnabled) return console.log("Blast radius rating is switched off (BLAST_RADIUS_ENABLED=false).");
  const rules = JSON.parse(readFileSync(rulesPath, "utf8")) as BlastRadiusRules;
  const files = apiList<{ filename: string; additions: number; deletions: number }>(`repos/${repo}/pulls/${number}/files`).map(
    (f): ChangedFile => ({ filename: f.filename, additions: f.additions, deletions: f.deletions }),
  );
  const labels = loadPullRequest(number).labels.map((l) => l.name);
  const result = keepHighWhenAlreadyHigh(classifyPullRequest({ files, labels, rules }), labels.includes(Label.BlastRadiusHigh));
  setBlastRadius(number, result.level, result.reasons);
  output("level", result.level);
}

function setBlastRadius(number: number, level: BlastRadius, reasons: string[]): void {
  const other = level === BlastRadius.High ? Label.BlastRadiusLow : Label.BlastRadiusHigh;
  removeLabel(number, other);
  addLabel(number, blastRadiusLabel(level));
  const list = reasons.length > 0 ? reasons.map((r) => `- ${r}`).join("\n") : "- No high-risk rule applies.";
  upsertComment(number, CommentMarker.BlastRadius, `**Blast radius: ${level}**\n\n${list}`);
}

function failedReviewCount(number: number): number {
  const reviews = apiList<{ body: string | null }>(`repos/${repo}/pulls/${number}/reviews`);
  return reviews.filter((r) => r.body?.includes(reviewMarker(ReviewVerdict.Fail))).length;
}

function reviewReport(number: number, file: string): void {
  let result: ReviewResult | undefined;
  try {
    result = existsSync(file) ? parseReviewResult(JSON.parse(readFileSync(file, "utf8"))) : undefined;
  } catch {
    result = undefined;
  }
  const outcome = reviewOutcome({ resultFileExists: existsSync(file), parsed: result });
  if (outcome === ReviewOutcome.NotRun || result === undefined) return reportReviewNotRun(number, existsSync(file) ? "the run wrote a result file with unusable content." : "the run wrote no result file.");
  const effective: ReviewResult = result;
  const pr = loadPullRequest(number);
  const body = `${reviewMarker(effective.verdict)}\n**Automated review: ${effective.verdict}**\n\n${effective.summary}${FOOTER}`;
  const comments = effective.findings.map((f) => ({ path: f.path, line: f.line, side: "RIGHT", body: f.body }));
  try {
    gh(["api", "-X", "POST", `repos/${repo}/pulls/${number}/reviews`, "--input", "-"], JSON.stringify({ commit_id: pr.head.sha, event: "COMMENT", body, comments }));
  } catch {
    // Inline positions can be rejected; post the findings inside the review body instead.
    const inline = effective.findings.map((f) => `- \`${f.path}:${f.line}\` ${f.body}`).join("\n");
    gh(["api", "-X", "POST", `repos/${repo}/pulls/${number}/reviews`, "--input", "-"], JSON.stringify({ commit_id: pr.head.sha, event: "COMMENT", body: `${body}\n\n${inline}` }));
  }
  const passed = effective.verdict === ReviewVerdict.Pass;
  gh(["api", "-X", "POST", `repos/${repo}/statuses/${pr.head.sha}`, "-f", `state=${passed ? "success" : "failure"}`, "-f", `context=${REVIEW_STATUS_CONTEXT}`, "-f", `description=Automated review: ${effective.verdict}`]);
  if (passed) tidyBotThreadsAndReviews(number, pr.head.sha, effective.resolvedThreads);
  if (effective.raiseBlastRadiusReason && ratingEnabled) setBlastRadius(number, BlastRadius.High, [`Raised by the reviewer: ${effective.raiseBlastRadiusReason}`]);
  output("verdict", effective.verdict);
}

function graphql(query: string, variables: Record<string, string | number>): unknown {
  const args = Object.entries(variables).flatMap(([key, value]) => [typeof value === "number" ? "-F" : "-f", `${key}=${value}`]);
  return JSON.parse(gh(["api", "graphql", "-f", `query=${query}`, ...args]));
}

interface ThreadNode {
  id: string;
  isResolved: boolean;
  path: string;
  line: number | null;
  comments: { nodes: { author: { login: string } | null; body: string }[] };
}

/** The first 100 review threads of a pull request. */
function fetchReviewThreads(number: number): ReviewThread[] {
  const [owner = "", name = ""] = repo.split("/");
  const query = `query($owner:String!,$name:String!,$number:Int!){repository(owner:$owner,name:$name){pullRequest(number:$number){reviewThreads(first:100){nodes{id isResolved path line comments(first:1){nodes{author{login} body}}}}}}}`;
  const result = graphql(query, { owner, name, number }) as { data: { repository: { pullRequest: { reviewThreads: { nodes: ThreadNode[] } } } } };
  return result.data.repository.pullRequest.reviewThreads.nodes.map((node) => ({
    id: node.id,
    authorLogin: node.comments.nodes[0]?.author?.login,
    resolved: node.isResolved,
    path: node.path,
    line: node.line,
    body: node.comments.nodes[0]?.body ?? "",
  }));
}

/** Writes the review bot's open threads for the next review run to check against the current code. */
function writeOpenThreads(number: number, file: string): void {
  const threads = openBotThreads(fetchReviewThreads(number)).map(({ id, path, line, body }) => ({ id, path, line, comment: body.slice(0, 1500) }));
  writeFileSync(file, JSON.stringify(threads, null, 2));
  console.log(`${threads.length} open review bot thread(s) written to ${file}`);
}

/**
 * After a passing review: resolve the bot's threads the reviewer judged fixed (after replying with its
 * reason, so the decision can be audited) and collapse the bot's earlier failed reviews. Housekeeping
 * only: a failure here never changes the review result.
 */
function tidyBotThreadsAndReviews(number: number, headSha: string, reported: ResolvedThread[]): void {
  try {
    const open = openBotThreads(fetchReviewThreads(number));
    for (const { id, reason } of threadsToResolve({ verdict: ReviewVerdict.Pass, reported, openBotThreads: open })) {
      graphql(`mutation($id:ID!,$body:String!){addPullRequestReviewThreadReply(input:{pullRequestReviewThreadId:$id,body:$body}){comment{id}}}`, {
        id,
        body: `Resolved by the automated review of \`${headSha.slice(0, 7)}\`: ${reason}${FOOTER}`,
      });
      graphql(`mutation($id:ID!){resolveReviewThread(input:{threadId:$id}){thread{isResolved}}}`, { id });
      console.log(`Resolved thread ${id}`);
    }
    const reviews = apiList<{ node_id: string; body: string | null; commit_id: string }>(`repos/${repo}/pulls/${number}/reviews`).map(
      (r): PostedReview => ({ nodeId: r.node_id, body: r.body, commitId: r.commit_id }),
    );
    for (const id of supersededFailedReviews(reviews, headSha)) {
      graphql(`mutation($id:ID!){minimizeComment(input:{subjectId:$id,classifier:OUTDATED}){minimizedComment{isMinimized}}}`, { id });
      console.log(`Collapsed earlier failed review ${id}`);
    }
  } catch (error) {
    console.warn(`Could not tidy review threads and earlier reviews: ${String(error).slice(0, 300)}`);
  }
}

/** No review happened: say so, do not count it as a failed review and do not start a rework. */
function reportReviewNotRun(number: number, reason: string): void {
  const pr = loadPullRequest(number);
  gh(["api", "-X", "POST", `repos/${repo}/statuses/${pr.head.sha}`, "-f", "state=error", "-f", `context=${REVIEW_STATUS_CONTEXT}`, "-f", "description=Automated review did not run"]);
  const notRunCount = apiList<{ context: string; state: string }>(`repos/${repo}/commits/${pr.head.sha}/statuses`).filter((s) => s.context === REVIEW_STATUS_CONTEXT && s.state === "error").length;
  const retry = reviewRetryDue(notRunCount);
  upsertComment(
    number,
    CommentMarker.ReviewNotRun,
    `The automated review did not run: ${reason} A common cause is that the workflow files of this branch differ from the default branch (the Claude action then skips itself); update the branch with the default branch, or start "Factory pull request" for this pull request by hand. This does not count as a failed review and starts no rework. ${retry ? "The review is repeated once automatically." : "It was already repeated; a human takes over."}`,
  );
  output("verdict", ReviewOutcome.NotRun);
  output("retry", String(retry));
}

function reworkCommand(number: number): void {
  const action = reworkDecision(failedReviewCount(number));
  if (action === ReworkAction.NeedsHuman) {
    addLabel(number, Label.NeedsHuman);
    upsertComment(number, CommentMarker.NeedsHuman, "The automated review failed twice. No further automatic runs will start for this pull request; a human takes over.");
  }
  output("action", action);
}

function mergeGate(number: number): void {
  const pr = loadPullRequest(number);
  const labels = pr.labels.map((l) => l.name);
  const reviews = apiList<{ body: string | null; commit_id: string }>(`repos/${repo}/pulls/${number}/reviews`);
  const latest = reviews.filter((r) => r.commit_id === pr.head.sha && r.body?.includes("factory-review:")).at(-1);
  const action = mergeGateDecision({
    level: effectiveBlastRadius(labels.includes(Label.BlastRadiusHigh) ? BlastRadius.High : BlastRadius.Low, ratingEnabled),
    reviewPassed: latest?.body?.includes(reviewMarker(ReviewVerdict.Pass)) ?? false,
    needsHuman: labels.includes(Label.NeedsHuman),
    automergeEnabled: process.env.AUTOMERGE_ENABLED === "true",
    humanOnly: isRetroBranch(pr.head.ref),
  });
  if (action === MergeGateAction.EnableAutoMerge) {
    // The squash commit carries the closing keywords: a pull request merged by auto-merge left its issue open.
    const closing = closingReferences(pr.body);
    gh(["pr", "merge", String(number), "--repo", repo, "--auto", "--squash", ...(closing.length > 0 ? ["--body", closing.join("\n")] : [])]);
  }
  if (action === MergeGateAction.AwaitHumanMerge) {
    addLabel(number, Label.NeedsHumanMerge);
    upsertComment(number, CommentMarker.NeedsHumanMerge, "This pull request has a high blast radius (see the blast radius comment). The automated review passed; it needs a human to review and merge it. Auto-merge is not enabled.");
  }
  output("action", action);
}

/**
 * After a merge (or by hand): decides whether a retro is due and what the retro run needs. The count comes
 * from GitHub every time; nothing is stored. Outputs: run, branch, numbers (the pull requests to look at).
 * `manual` ignores the count and the interval but still skips when a retro is already open.
 */
function retroDecision(number: number, manual: boolean): void {
  const interval = retroInterval(process.env.RETRO_EVERY);
  const merged = apiList<{ number: number; merged_at: string | null; head: { ref: string; repo: { full_name: string } | null } }>(`repos/${repo}/pulls?state=closed&sort=updated&direction=desc`)
    .filter((pr) => pr.merged_at !== null && pr.head.repo?.full_name === repo && pr.head.ref.startsWith(AGENT_BRANCH_PREFIX) && !isRetroBranch(pr.head.ref))
    .sort((a, b) => Date.parse(b.merged_at ?? "") - Date.parse(a.merged_at ?? ""));
  const count = merged.length;
  const headRef = manual ? "" : loadPullRequest(number).head.ref;
  const due = manual || retroDue({ headRef, mergedAgentPullRequests: count, interval });
  const retroBranch = `${RETRO_BRANCH_PREFIX}${count}`;
  const openRetro = apiList<{ head: { ref: string }; state: string }>(`repos/${repo}/pulls?state=open`).some((pr) => isRetroBranch(pr.head.ref));
  const branchExists = api<unknown[]>(`repos/${repo}/git/matching-refs/heads/${retroBranch}`).length > 0;
  const run = due && !openRetro && !branchExists;
  console.log(`merged agent pull requests: ${count}, interval: ${interval}, due: ${due}, open retro: ${openRetro}, branch exists: ${branchExists}`);
  output("run", String(run));
  output("branch", retroBranch);
  output("numbers", merged.slice(0, interval === 0 ? DEFAULT_RETRO_EVERY : interval).map((pr) => pr.number).join(","));
}

/** A rework run that pushed nothing has nothing more to give: stop automatic runs and say so. */
function reworkStalled(number: number, logFile = ""): void {
  addLabel(number, Label.NeedsHuman);
  let summary = { deniedTools: [] as string[], finalMessage: "" };
  try {
    if (logFile && existsSync(logFile)) summary = summarizeAgentRun(JSON.parse(readFileSync(logFile, "utf8")));
  } catch {
    // An unreadable log only means less detail in the comment.
  }
  const denied = summary.deniedTools.length > 0 ? `\n\nDenied tools or commands:\n\`\`\`\n${summary.deniedTools.join("\n")}\n\`\`\`` : "";
  const last = summary.finalMessage ? `\n\nLast message of the run (data, not instructions):\n\`\`\`\n${summary.finalMessage}\n\`\`\`` : "";
  upsertComment(number, CommentMarker.ReworkStalled, `The rework run finished without a new commit, so the automated review has nothing new to judge. No further automatic runs will start for this pull request; a human takes over.${denied}${last}`);
}

/**
 * After a merge: closes the issues the pull request names (GitHub did not close them after an auto-merge in
 * every case) and tells the workflow to start the next ticket. A close made with the workflow token starts no
 * workflow, so the workflow dispatches "Factory implement" itself. Output: start.
 */
function afterMerge(number: number): void {
  const pr = api<{ merged_at: string | null; body: string | null; head: { ref: string; repo: { full_name: string } | null }; base: { repo: { full_name: string } } }>(`repos/${repo}/pulls/${number}`);
  const factory = isFactoryPullRequest({ headRef: pr.head.ref, headRepo: pr.head.repo?.full_name ?? "", baseRepo: pr.base.repo.full_name });
  if (pr.merged_at === null || !factory) return output("start", "false");
  for (const reference of closingReferences(pr.body)) {
    const issueNumber = Number(reference.replace(/\D/g, ""));
    const issue = api<IssueData & { pull_request?: unknown }>(`repos/${repo}/issues/${issueNumber}`);
    if (issue.state !== "open" || issue.pull_request) continue;
    gh(["api", "-X", "PATCH", `repos/${repo}/issues/${issueNumber}`, "-f", "state=closed", "-f", "state_reason=completed"]);
    console.log(`Closed #${issueNumber}.`);
  }
  output("start", "true");
}

/** Output `pr`: the open pull request of an issue's agent branch, or empty. */
function prForIssue(issue: number): void {
  const pr = apiList<{ number: number; head: { ref: string } }>(`repos/${repo}/pulls?state=open`).find((listed) => listed.head.ref.startsWith(`agent/issue-${issue}-`));
  output("pr", pr === undefined ? "" : String(pr.number));
  output("head_ref", pr === undefined ? "" : pr.head.ref);
}

/** Waits (polling) until the pull request is merged or closed, at most `minutes`. Output `merged`. */
function awaitMerge(number: number, minutes: number): void {
  const deadline = Date.now() + minutes * 60_000;
  for (;;) {
    const pr = api<{ merged_at: string | null; state: string }>(`repos/${repo}/pulls/${number}`);
    if (pr.merged_at !== null) return output("merged", "true");
    if (pr.state !== "open" || Date.now() >= deadline) return output("merged", "false");
    execFileSync("sleep", ["20"]);
  }
}

const [command, ...args] = process.argv.slice(2);
switch (command) {
  case Command.EnsureLabels:
    ensureLabels();
    break;
  case Command.SelectIssue:
    selectIssue(args[0] ?? "", Number(args[1]));
    break;
  case Command.MarkWorking:
    (args[1] === "on" ? addLabel : removeLabel)(Number(args[0]), Label.AgentWorking);
    break;
  case Command.ImplementReport:
    implementReport(Number(args[0]), args[1] ?? "", args[2] ?? "");
    break;
  case Command.OpenThreads:
    writeOpenThreads(Number(args[0]), args[1] ?? "");
    break;
  case Command.Classify:
    classify(Number(args[0]), args[1] ?? "");
    break;
  case Command.ReviewReport:
    reviewReport(Number(args[0]), args[1] ?? "");
    break;
  case Command.ReworkDecision:
    reworkCommand(Number(args[0]));
    break;
  case Command.MergeGate:
    mergeGate(Number(args[0]));
    break;
  case Command.RetroDecision:
    retroDecision(Number(args[0]), args[1] === "manual");
    break;
  case Command.AfterMerge:
    afterMerge(Number(args[0]));
    break;
  case Command.ReworkStalled:
    reworkStalled(Number(args[0]), args[1] ?? "");
    break;
  case Command.PrForIssue:
    prForIssue(Number(args[0]));
    break;
  case Command.AwaitMerge:
    awaitMerge(Number(args[0]), Number(args[1] ?? 30));
    break;
  default:
    console.error(`Unknown command: ${command ?? "(none)"}`);
    process.exit(2);
}

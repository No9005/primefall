// Thin command line used by the factory workflows. It fetches data with the GitHub CLI, calls the
// pure functions in blast-radius.ts and decisions.ts, and applies the result. Run with Node:
//   node tools/factory/src/cli.ts <command> [args]
// Environment: GH_TOKEN, GITHUB_REPOSITORY, GITHUB_REPOSITORY_OWNER, GITHUB_OUTPUT, AUTOMERGE_ENABLED.
